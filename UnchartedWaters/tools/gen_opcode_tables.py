#!/usr/bin/env python3
"""Generate the 65816 / SPC700 opcode tables used by the disassembler.

The 65816 table is derived from WLA DX' own instruction table
(``i65816.c``), so the disassembler always agrees with the assembler we
use to build the ROM.  Point the script at a WLA checkout with
``--wla /path/to/wla-dx``.

The SPC700 table comes from the reference ``spcdas`` disassembler.

Usage:
    python3 tools/gen_opcode_tables.py --wla ~/tools/wla-dx [--spcdas file.cpp]
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT_DIR = HERE / "ucw"

BRANCHES_REL = {"BPL", "BMI", "BVC", "BVS", "BCC", "BCS", "BNE", "BEQ", "BRA"}


def classify(mnemonic: str) -> tuple[str, int]:
    """Return (mode, operand byte count) for a WLA style mnemonic."""
    text = mnemonic.strip()
    name = text.split()[0].split(".")[-1]
    if name in BRANCHES_REL:
        return "rel", 1
    if name in {"PER", "BRL"}:
        return "rel16", 2
    if name == "PEA":
        return "abs", 2
    if name in {"MVN", "MVL", "MVP"}:
        return "block", 3
    # Normalise WLA's address size markers so the patterns below match.
    norm = text.replace("<x", "x")
    if "[|?]" in text or "[?]" in text:
        return "indlongabs", 3
    if "(|?,X)" in text or "(?,X)" in text:
        return "absidx", 2
    if "&" in text:
        return "long", 3
    norm = norm.replace("|?", "?").replace(">?", "?").replace(">", "")
    if "#" in norm:
        return "imm8", 1
    if "[x]" in norm:
        # The long indirect forms take the high byte of the pointer from the
        # direct page bank register, so they are only one byte long.
        return "indlong", 1
    if "(x,S),Y" in norm:
        return "sry", 1
    if "(x,X)" in norm:
        return "indx", 1
    if "(x),Y" in norm:
        return "indy", 1
    if "(x)" in norm:
        return "ind", 1
    if "x,S" in norm:
        return "sr", 1
    if ",X" in norm or ",Y" in norm:
        return ("absidx", 2) if "?" in norm else ("dpidx", 1)
    if "?" in norm:
        return "abs", 2
    if "x" in norm:
        return "dp", 1
    if name in {"ASL", "LSR", "ROL", "ROR"}:
        return "acc", 0
    return "imp", 0


def parse_wla(path: Path) -> dict[int, tuple[str, str, int, str]]:
    """Parse WLA's i65816.c into {opcode: (mnemonic, mode, size, template)}."""
    text = path.read_text()
    entries = re.findall(
        r'\{\s*"([^"]+)"\s*,\s*0x([0-9A-Fa-f]{2})\s*,\s*([^,]+),\s*(\d+)\s*\}', text
    )
    table: dict[int, tuple[str, str, int, str]] = {}
    for mnemonic, opcode, _typ, _flags in entries:
        op = int(opcode, 16)
        plain = not re.search(r"\.[BWL] ", mnemonic)
        if op in table:
            existing_plain = not re.search(r"\.[BWL] ", table[op][0])
            if existing_plain or not plain:
                # keep the plain spelling when we already have one
                continue
        mode, operand_size = classify(mnemonic)
        name = mnemonic.split()[0].split(".")[-1]
        template = mnemonic.split(None, 1)[1] if " " in mnemonic else ""
        table[op] = (name, mode, 1 + operand_size, template)
    return table


def parse_spc700(path: Path) -> dict[int, tuple[int, str, list[int]]]:
    """Parse the reference spcdas table."""
    text = path.read_text()
    out: dict[int, tuple[int, str, list[int]]] = {}
    for match in re.finditer(
        r'case 0x([0-9a-fA-F]{2}):\s*disas\((\d+),\s*"([^"]*)"([^)]*)\);', text
    ):
        op = int(match.group(1), 16)
        size = int(match.group(2))
        fmt = match.group(3)
        args = [int(x) for x in re.findall(r"(\d+)", match.group(4))]
        out[op] = (size, fmt, args)
    return out


def write_65816(table: dict[int, tuple[str, str, int, str]]) -> None:
    body = [
        '"""65816 opcode table.',
        "",
        "Generated by tools/gen_opcode_tables.py from the WLA DX instruction",
        "table (i65816.c), so the disassembler always agrees with the",
        "assembler we use to build the ROM.",
        '"""',
        "",
        "# opcode -> (mnemonic, mode, total instruction size in bytes, template)",
        "TABLE: dict[int, tuple[str, str, int, str]] = {",
    ]
    for op in sorted(table):
        mnemonic, mode, size, template = table[op]
        body.append(f"    0x{op:02X}: ({mnemonic!r}, {mode!r}, {size}, {template!r}),")
    body.append("}")
    body.append("")
    (OUT_DIR / "opcodes_65816.py").write_text("\n".join(body))
    print(f"wrote {OUT_DIR / 'opcodes_65816.py'} ({len(table)} opcodes)")


def write_spc700(table: dict[int, tuple[int, str, list[int]]]) -> None:
    body = [
        '"""SPC700 opcode table.',
        "",
        "Generated by tools/gen_opcode_tables.py from the reference `spcdas`",
        "disassembler.",
        '"""',
        "",
        "# opcode -> (instruction size in bytes, format string, operand offsets)",
        "TABLE: dict[int, tuple[int, str, list[int]]] = {",
    ]
    for op in sorted(table):
        size, fmt, args = table[op]
        body.append(f"    0x{op:02X}: ({size}, {fmt!r}, {args!r}),")
    body.append("}")
    body.append("")
    (OUT_DIR / "spc700_table.py").write_text("\n".join(body))
    print(f"wrote {OUT_DIR / 'spc700_table.py'} ({len(table)} opcodes)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--wla", type=Path, help="path to a wla-dx checkout")
    parser.add_argument("--spcdas", type=Path, help="path to spcdas.cpp")
    args = parser.parse_args()

    if args.wla:
        source = args.wla / "i65816.c"
        if not source.exists():
            print(f"error: {source} not found")
            return 1
        write_65816(parse_wla(source))
    if args.spcdas:
        write_spc700(parse_spc700(args.spcdas))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
