#!/usr/bin/env python3
"""Analyse the original Uncharted Waters ROM.

Prints the header, works out which memory mapping the cartridge uses and
writes a disassembly listing for every bank.

Usage:
    python3 tools/analyze.py [--rom PATH] [--out DIR]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from ucw.disasm import disassemble_65816, decode_65816  # noqa: E402
from ucw.map import MAPPINGS  # noqa: E402
from ucw.rom import Rom, checksum, checksum16  # noqa: E402
from ucw.trace import trace_rom  # noqa: E402

# Entry points taken from the cartridge's own vector table and jump table.
ENTRY_POINTS = [
    (0x00, 0x9593),  # native RESET
    (0x00, 0x8361),  # NMI
    (0x00, 0x8000),  # jump table at the start of the ROM
]


def describe_header(rom: Rom) -> None:
    print("=" * 72)
    print(f"ROM: {rom.path}")
    print(f"size: {rom.size} bytes (0x{rom.size:X})")
    print(f"sha256: {rom.sha256}")
    print(f"checksum: ${checksum(rom.data):02X}  (16 bit variant: ${checksum16(rom.data):04X})")
    print()
    print("--- standard header interpretation (offset 0x7FC0) ---")
    print(rom.header().describe())
    ext = rom.extended_header()
    print()
    print("--- extended header at 0xFFC0 ---")
    if ext:
        for key, value in ext.items():
            print(f"  {key:20}: {value}")
    else:
        print("  (none)")
    print()


def score_mappings(rom: Rom) -> None:
    """Trace each candidate mapping and report how much code it finds."""
    print("=" * 72)
    print("Memory mapping detection")
    print()
    for name, mapping in MAPPINGS.items():
        result = trace_rom(rom, mapping, ENTRY_POINTS)
        funcs = len(result.functions)
        code = len(result.code)
        unresolved = len(result.unresolved)
        print(
            f"  {name:9} functions={funcs:5} code bytes={code:6} "
            f"unresolved={unresolved:4}"
        )
    print()


def write_listings(rom: Rom, out_dir: Path, mapping_name: str) -> None:
    """Write one disassembly listing per 32 KiB bank."""
    mapping = MAPPINGS[mapping_name]
    out_dir.mkdir(parents=True, exist_ok=True)
    result = trace_rom(rom, mapping, ENTRY_POINTS)

    # Collect the code bytes per 32 KiB bank.
    per_bank: dict[int, set[int]] = {}
    for phys in result.code:
        bank, _ = mapping.from_phys(phys)
        if bank is None:
            continue
        per_bank.setdefault(bank, set()).add(phys)

    for bank in sorted(per_bank):
        code = per_bank[bank]
        path = out_dir / f"bank{bank:02X}.s"
        lines = [
            f"; Uncharted Waters (USA) - bank ${bank:02X} disassembly",
            "; generated by tools/analyze.py - hand editing welcome",
            "",
        ]
        start = 0x8000
        addr = start
        while addr <= 0xFFFF:
            phys = mapping.to_phys(bank, addr)
            if phys is None:
                addr += 1
                continue
            if phys in code:
                chunk = bytes(rom.data[phys : phys + 8])
                insn = decode_65816(chunk, addr)
                lines.append(f"{addr:04X}: {insn}")
                addr += insn.size
            else:
                lines.append(f"{addr:04X}: {rom.data[phys]:02X}        .byte ${rom.data[phys]:02X}")
                addr += 1
        path.write_text("\n".join(lines) + "\n")

    print(f"  wrote {len(per_bank)} bank listings to {out_dir}")
    print(f"  total traced code: {len(result.code)} bytes")
    print(f"  functions found   : {len(result.functions)}")
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rom", type=Path, default=None, help="path to the .sfc")
    parser.add_argument("--out", type=Path, default=None, help="output directory")
    parser.add_argument(
        "--mapping",
        default=None,
        choices=sorted(MAPPINGS),
        help="force a memory mapping (default: autodetect)",
    )
    args = parser.parse_args()

    rom = Rom(args.rom)
    describe_header(rom)
    score_mappings(rom)

    mapping_name = args.mapping
    if mapping_name is None:
        # Proven by reading the emulator's memory view back and comparing
        # it with the file image (see docs/memory-map.md).
        mapping_name = "lorom"

    out_dir = args.out or (Path(__file__).resolve().parents[1] / "build" / "disasm")
    print(f"Using mapping: {mapping_name}")
    write_listings(rom, out_dir, mapping_name)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
